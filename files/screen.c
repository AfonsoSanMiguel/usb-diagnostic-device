static void send_command(unsigned char cmd) {
    unsigned char buf[2] = { CTRL_CMD, cmd };
    write(i2c_fd, buf, 2);
}

int screen_init(void) {
    i2c_fd = open(I2C_DEVICE, O_RDWR);
    if (i2c_fd < 0) {
        fprintf(stderr, "Erro: nao foi possivel abrir %s\n", I2C_DEVICE);
        return -1;
    }

    if (ioctl(i2c_fd, I2C_SLAVE, OLED_ADDR) < 0) {
        fprintf(stderr, "Erro: nao foi possivel selecionar o OLED\n");
        close(i2c_fd);
        return -1;
    }

    send_command(0xAE);
    send_command(0xD5); send_command(0x80);
    send_command(0xA8); send_command(0x3F);
    send_command(0xD3); send_command(0x00);
    send_command(0x40);
    send_command(0x8D); send_command(0x14);
    send_command(0x20); send_command(0x00);
    send_command(0xA1);
    send_command(0xC8);
    send_command(0xDA); send_command(0x12);
    send_command(0x81); send_command(0xCF);
    send_command(0xD9); send_command(0xF1);
    send_command(0xDB); send_command(0x40);
    send_command(0xA4);
    send_command(0xA6);
    send_command(0xAF);
    screen_clear();
    screen_update();

    return 0;
}

void screen_cleanup(void) {
    if (i2c_fd >= 0) {
        send_command(0xAE);
        close(i2c_fd);
        i2c_fd = -1;
    }
}

void screen_clear(void) {
    memset(framebuffer, 0, sizeof(framebuffer));
}

void screen_update(void) {
    send_command(0x21); send_command(0);   send_command(127);
    send_command(0x22); send_command(0);   send_command(7);
    unsigned char chunk[17];
    chunk[0] = CTRL_DATA;

    for (size_t i = 0; i < sizeof(framebuffer); i += 16) {
        memcpy(&chunk[1], &framebuffer[i], 16);
        write(i2c_fd, chunk, 17);
    }
}

void screen_draw_text(int line, int col, const char *text, int inverted) {
    if (line < 0 || line >= SCREEN_LINES) return;
    if (text == NULL) return;
    int x = col;
    while (*text != '\0' && x < SCREEN_WIDTH - FONT_WIDTH) {
        char c = *text;
        if (c < 32 || c > 126) c = ' ';
        for (int i = 0; i < FONT_WIDTH; i++) {
            unsigned char byte = font[c - 32][i];
            if (inverted) byte = ~byte;
            framebuffer[line * SCREEN_WIDTH + x + i] = byte;
        }

        x += FONT_WIDTH;
        text++;
    }
}

void screen_draw_bar(int page, int percent) {
    if (page < 0 || page >= 8) return;
    if (percent < 0)   percent = 0;
    if (percent > 100) percent = 100;

    const int inner = SCREEN_WIDTH - 2;
    int fill = (inner * percent) / 100;

    framebuffer[page * SCREEN_WIDTH + 0]                  = 0xFF;
    framebuffer[page * SCREEN_WIDTH + (SCREEN_WIDTH - 1)] = 0xFF;

    for (int x = 1; x < SCREEN_WIDTH - 1; x++) {
        if ((x - 1) < fill) {

            framebuffer[page * SCREEN_WIDTH + x] = 0xFF;
        } else {

            framebuffer[page * SCREEN_WIDTH + x] = 0x81;
        }
    }
}
